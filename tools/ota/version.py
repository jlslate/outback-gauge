# PlatformIO pre-script: writes src/fw_version.cpp so the settings page can say
# which build is on the gauge. Only that one file is recompiled each build.
Import("env")
import subprocess, time, os

root = env["PROJECT_DIR"]

def git(*args):
    try:
        return subprocess.check_output(["git", "-C", root, *args], stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""

rev = git("rev-parse", "--short", "HEAD") or "unknown"
if git("status", "--porcelain", "--untracked-files=no"):
    rev += "+edits"
stamp = time.strftime("%Y-%m-%d %H:%M")

with open(os.path.join(root, "src", "fw_version.cpp"), "w") as f:
    f.write('// Generated by tools/ota/version.py on every build; not committed.\n')
    f.write('#include "fw_version.h"\n\nconst char *const FW_VERSION = "%s %s";\n' % (rev, stamp))
